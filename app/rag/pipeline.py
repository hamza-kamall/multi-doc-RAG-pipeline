# Fast model for routing, grading, and query generation.
settings = get_settings()
fast_llm = ChatGroq(
    model=settings.groq_model,
    api_key=settings.groq_api_key,
    temperature=0
)

class web_search(BaseModel):
    """The internet.Use web_search for any query other than RAG-related."""
    query: str = Field(..., description="The query to search the web for.")

class vectorstoresearch(BaseModel):
    """The vector store. Use vectorstore for RAG-related queries."""
    query: str = Field(..., description="The query to search the vectorstore for.")

# Router instructions: choose between vector search, web search, or no tool.
preamble = """
You are a routing assistant.

Rules:
- Use vectorstore ONLY for RAG/Retrieval-Augmented Generation .
- Use web_search ONLY for weather, news, current events, and internet knowledge.
- If no tool is needed, answer normally without calling any tool call.

DONOT GIVE REASONING FOR YOUR APPROACH TO THE USER. ALWAYS ANSWER IN A CONCISE STRING MANNER.
"""

# Bind the tool schemas so the model can return a tool call as its routing decision.
structured_llm_output = fast_llm.bind_tools(tools=[web_search, vectorstoresearch])

prompt = ChatPromptTemplate.from_messages([
    ("system", preamble),
    ("human","{query}")
])

question_router = prompt | structured_llm_output

class grading(BaseModel):
    """The grading tool.It gives a score based on the relevance of the retrieved documents to the query."""
    score : Literal["yes", "no"] = Field(...,
                        description = 'Documents are relevant to the query. "Yes" or "No"')
    
# Relevance grader instructions.
preamble = """You are a grading assistant. You will be given a query and a set of retrieved documents. Your \n
if the retrieved document contains any keyword(s) or any semantic meaning related to the query, then return \n 
'yes' otherwise return 'no'. Always answer in yes or no only. Do not give any explanation."""

# Chain that grades whether a retrieved document should be kept.
structured_grading_output = fast_llm.with_structured_output(grading)

grading_prompt = ChatPromptTemplate.from_messages([
    ("system", preamble),
    ("human","query : {query} \n retrieved_docs : {retrieved_docs}")])

retrieval_grader = grading_prompt | structured_grading_output

class GradeHallucination(BaseModel):
    """The hallucination grader. It checks if the answer generated by the LLM is present in the retrieved documents."""
    hall_score : Literal["yes", "no"] = Field(...,
                        description = 'Answer is grounded to the retrieved documents. "Yes" or "No"')
    
# Chain that verifies the generated answer is supported by retrieved context.
structured_llm = fast_llm.with_structured_output(GradeHallucination)

prompt = ChatPromptTemplate.from_messages([
    ("system", """You are a hallucination grading assistant. your job is to check whether the answer is grounded/supported with the retrieved documents.\n
     "yes" if the answer is grounded/supported and "no" if the answer is not grounded/supported. Always answer in yes or no only. Do not give any explanation."""),
     ("human","query : {query} \n retrieved_docs : {retrieved_docs} \n answer : {answer}")
])

hallucination_grader = prompt | structured_llm

class grader(BaseModel):
    """it checks whether the answer reolves the query or not. It gives a score of "yes" if the answer resolves the query and "no" if it does not resolve the query."""
    score : Literal["yes", "no"] = Field(description = 'Answer resolves the query. "Yes" or "No"')

# Chain that checks whether the answer is useful for the original question.
structured_llm = fast_llm.with_structured_output(grader)

prompt = ChatPromptTemplate.from_messages([
    ("system", """You are a grading assistant. Your job is to check whether the answer resolves the query or not. "Yes" if the answer resolves the query and "No" if it does not resolve the query. Always answer in yes or no only. Do not give any explanation."""),
    ("human","query : {query} \n answer : {answer}")
])

answer_grader = prompt | structured_llm
#print(answer_grader.invoke({"query": question, "answer": generation}))

##SEARCH ENGINE
# Tavily is used when routing chooses web search or local retrieval is insufficient.
class GraphState(TypedDict, total=False):
    """Represents the state of the graph 
    question : question 
    generation : llm output 
    documents : list of retrieved documents """

    question : str
    questions : List[str]
    generation : str
    documents : List[Document]
    document_id : str
    retry_count : int


def app(retriever) :
    
    # Generate multiple alternate versions of the question for broader retrieval.
    def generate_queries(state: GraphState) -> dict:
        alternatives = generate_alternate_queries(state["question"])
        return {"questions": [state["question"], *alternatives]}


    def retrieve(state: GraphState) -> GraphState:
        """retrieves the docs from vector db based on the question 
        """

        retrieved_docs = retriever.map().invoke(state["questions"])
        RRF_docs = RRF(retrieved_docs)
        compressed_docs = reranker(state["question"], RRF_docs)["documents"]
        return {"documents" : compressed_docs}

        
        



    def llm_fallback(state: GraphState):
        """the llm answers on its own without retrieval and without using any tool"""
        question = state["question"]
        answer = generate_general_answer(question)
        return {"generation" : answer}

    def generate(state: GraphState) :
        """Generates an answer based on the retrieved documents and the question"""
        print("----GENERATE----")
        question = state["question"]
        if not isinstance(state["documents"],list) :
            state["documents"] = [state["documents"]]
        context = "\n\n".join(doc.page_content for doc in state["documents"])
        answer = generate_answer(question=question, context=context)
        retry_count = state.get("retry_count", 0) + 1
        return {"generation" : answer, "retry_count" : retry_count}

    def grade_documents(state:GraphState) :
        """goes throught all the retrieved documents and checks their relevance to the question.
        If the documents are not relevant, it returns "no" and if they are relevant, it returns "yes" """
        
        f_docs = [] 
        for doc in state["documents"] :
            result = retrieval_grader.invoke({"query": state["question"], "retrieved_docs": doc.page_content})
            if result.score == "yes" :
                print("GRADING RESULT : YES")
                f_docs.append(doc)
            else :
                print("GRADING RESULT : NO")
        return({"documents" : f_docs})

    def web_search(state: GraphState) :
        """calls the web search tool to get more information about the question"""
        print("----WEB SEARCH----")
        question = state["question"]
        if not settings.tavily_api_key:
            raise RuntimeError("TAVILY_API_KEY is required for web search")
        wrapper = TavilySearchAPIWrapper(tavily_api_key=settings.tavily_api_key)
        web_search_tool = TavilySearchResults(
            api_wrapper=wrapper,
            max_results=5,
        )
        search_results = web_search_tool.invoke({"query" : question})
        res = [Document(
            page_content=result["content"],
            metadata={"source": result.get("url", "unknown"), "source_type": "web"},
        ) for result in search_results]
        return {"documents" : res}
 

    ## EDGES 

    def route_question(state: GraphState) -> str :
        """routes the question to either retrieval or web search based on the question type"""
        
        question = state["question"]
        source = question_router.invoke({"query": question})
        if not "tool_calls" in source.additional_kwargs:
            return "llm_fallback"
        elif len(source.additional_kwargs["tool_calls"]) == 0 :
            raise RuntimeError("Router cannot decide source")

        if source.additional_kwargs["tool_calls"][0]["function"]["name"] == "vectorstoresearch" :
            print("ROUTER RESULT : VECTORSTORESEARCH/RAG")
            return "vectorstoresearch"
        elif source.additional_kwargs["tool_calls"][0]["function"]["name"] == "web_search" :
            print("ROUTER RESULT : WEB_SEARCH")
            return "web_search"
        else :
            print("Routing question to LLM")
            return "vectorstoresearch"
        
    def decide_to_generate(state:GraphState) :
        print("----Access graded documents----")
        
        f_docs = state["documents"]
        if not f_docs :
            print("No relevant documents.Web Searching...")
            return "web_search"
        else :
            print("Relevant documents found. Generating answer...")
            return "generate"

    def grade_generation_w_question_answer(state:GraphState) :
        """Checks whether the generation is grounded to the retrieved documents or not."""
        question = state["question"]
        generation = state["generation"]
        docs = state["documents"]

        # Hallucination grading needs all document text as one context string.
        context = "\n\n".join([doc.page_content for doc in docs])

        score = hallucination_grader.invoke({"query": question, "retrieved_docs": context, "answer": generation})
        if score.hall_score == "yes" :
            print("Generation is grounded to the retrieved documents.")
            print("Checking if answer resolves the question...")
            score2 = answer_grader.invoke({"query": question, "answer": generation})
            if score2.score == "yes" :
                print("Answer resolves the question. Returning answer...")
                return "useful"
            else :
                print("Answer doesnt resolves the question.")
                if state.get("retry_count", 0) >= 3:
                    return "end"
                return "not useful"
        else :
            print("Generation is not grounded to the retrieved documents.")
            if state.get("retry_count", 0) >= 3:
                return "end"
            return "not grounded"


    workflow = StateGraph(GraphState)
    workflow.add_node("generate_queries", generate_queries)
    workflow.add_node("retrieve", retrieve)
    workflow.add_node("grade_documents", grade_documents)
    workflow.add_node("web_search", web_search) 
    workflow.add_node("generate", generate)
    workflow.add_node("llm_fallback", llm_fallback) 

    # First edge: route the user question to the right starting node.
    workflow.add_conditional_edges(
        START,
        route_question,{
            "vectorstoresearch" : "generate_queries",
            "web_search" : "web_search",
            "llm_fallback" : "llm_fallback"
        }
    )

    # Retrieval/web-search results are both passed into the generator.
    workflow.add_edge("generate_queries","retrieve")
    workflow.add_edge("retrieve","grade_documents")
    workflow.add_edge("web_search","generate")


    # If retrieved documents are relevant, generate. Otherwise, fall back to web search.
    workflow.add_conditional_edges(
        "grade_documents",
        decide_to_generate,{
            "web_search" : "web_search",
            "generate" : "generate"
        }
    )



    # After generation, either finish, search the web, or retry generation.
    workflow.add_conditional_edges(
        "generate",
        grade_generation_w_question_answer,{
            "useful" : END  ,
            "not useful" : "web_search",
            "not grounded" : "generate",
            "end" : END
        }
    )

    workflow.add_edge("llm_fallback",END)

    # Compile the graph into a runnable RAG application.
    rag_app = workflow.compile()

    return rag_app
            


